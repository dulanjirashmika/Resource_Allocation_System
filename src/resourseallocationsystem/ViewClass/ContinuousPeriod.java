    private void calDatesButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calDatesButtonActionPerformed
        // TODO add your handling code here:
        try{
        SimpleDateFormat sdf = new SimpleDateFormat("MMM d, y", Locale.ENGLISH);
        Date firstDate = firstDateChooser.getDate();
        Date lastDate = lastDateChooser.getDate();
        
        long diffInMillies = Math.abs(lastDate.getTime() - firstDate.getTime());
        long diff = TimeUnit.DAYS.convert(diffInMillies,TimeUnit.MILLISECONDS);
        
        noOfDatesText.setText(String.valueOf(diff+1));
        }
        catch(Exception e){
            e.printStackTrace();
            
        }
                
        
    }//GEN-LAST:event_calDatesButtonActionPerformed

