            String sql = "INSERT INTO continuousperiod"
                    +"(firstDate,lastDate,noOfDates)"
                    +"VALUES (?,?,?)";
            con = (Connection) DriverManager.getConnection("jdbc:mysql://localhost/resource allocation system","root","");
            pat = con.prepareStatement(sql);
            
            pat.setString(1,((JTextField)firstDateChooser.getDateEditor().getUiComponent()).getText());
